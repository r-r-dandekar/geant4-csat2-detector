"""
Filters only the photon entries from the consolidated .csv (generated by consolidate_timelogs.py)

EXAMPLE USAGE
python isolate_photons_in_consolidated.py --input="../results/$SUBDIR/consolidated.csv" --output="../results/$SUBDIR/consolidated_photons_only.csv"
"""

import pandas as pd
from pathlib import Path
import argparse

if __name__ == "__main__":
    parser = argparse.ArgumentParser(
        description='Filter photon events only from proton+photon consolidated csv file'
    )
    parser.add_argument('--input', type=Path, default=Path('consolidated.csv'),
                        help='Output CSV path (default: consolidated.csv)')
    parser.add_argument('--output', type=Path, default=Path('consolidated_photons_only.csv'),
                        help='Output CSV path (default: consolidated.csv)')
    args = parser.parse_args()

# Load the consolidated dataset
df = pd.read_csv(args.input)

# Filter out rows where the 'particle' column is 'proton'
filtered_df = df[df['particle'] != 'proton']

# Save the resulting dataframe to a new CSV file
filtered_df.to_csv(args.output, index=False)

print(f"Filtering complete. Data saved to {args.output}.")